#!/usr/bin/env python3
"""倉庫卡片底部綠字「0轉1級」判斷（1920×1017；純標準庫，不用 OCR）。

背景（2026-10-12 使用者）：個人 / 公共倉庫每張寵物卡片底部有綠字「0轉N級」，字只有約 8 像素高，
Windows OCR 讀不出來（試過 -Dark / -Light / -Green 都不行）。所以改成像素比對：
  1. 取卡片底部 68×24 區塊，綠字遮罩（G>150、G-R>50、G-B>90）
  2. 與「0轉1級」樣板（取自 11111 倉庫巴朵蘭恩卡片）比 IoU（左右平移 ±4 px）
  3. 整體 IoU >= {GLOBAL_MIN} 且「數字 1 的窗口」IoU >= {WINDOW_MIN} 才算 1 級
     （1 級以外的實測：133 / 136 / 132 級整體 IoU 0.33~0.36、窗口 0.47；真正的 1 級 0.77/0.71（2026-10-13 11111 角色 1 朵拉比斯，原門檻 0.70/0.80 誤判）→ 門檻改 0.60/0.60）
只判斷「是不是 1 級」；2~9 級的數字窗口形狀不同，窗口 IoU 會很低（沒有實物樣本，未實測）。
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

HALF_W = 34                  # 卡片中心左右各取多寬
LABEL_DY0, LABEL_H = 6, 24   # 取樣列：卡片中心 y + 6 起、共 24 列（卡片列中心 y=170 時文字約在 y=181~190）
GLOBAL_MIN = 0.60
WINDOW_MIN = 0.60
WIN_LO_OFF, WIN_HI_OFF = 19, 26   # 數字窗口：樣板文字左緣 + 19 ~ + 26 欄
SHIFTS = range(-4, 5)

TEMPLATE = [
    '....................................................................',
    '....................................................................',
    '....................................................................',
    '....................................................................',
    '.......................##....##............#..######................',
    '.................#....###########....#.....#...#####................',
    '...............####....##..######..###....#.##.##.##................',
    '...............##.##..####.######...##...####..##.##................',
    '...............#..##..####.######....#....###..##.###...............',
    '...............#..##..####...####....#....##.#.##..##...............',
    '...............#..##..###########....#....####.##..##...............',
    '...............#..##...##..#..###....#.........###.#................',
    '...............##.##...##.#######....#.......#.#.###................',
    '................###...####..#..#...#####.#######.###................',
    '.................#.....##...#.##...#####.####.####.##...............',
    '..............................#.................#...#...............',
    '....................................................................',
    '....................................................................',
    '....................................................................',
    '....................................................................',
    '....................................................................',
    '....................................................................',
    '....................................................................',
    '....................................................................'
]


def green_mask(rows, bpp, cx: int, cy: int) -> list:
    """解碼後的 PNG（pngread.decode 的 rows / bpp）→ 以 (cx, cy) 為卡片中心的綠字遮罩 [[0/1]×68]×24"""
    out = []
    for yy in range(cy + LABEL_DY0, cy + LABEL_DY0 + LABEL_H):
        r = rows[yy]
        line = []
        for xx in range(cx - HALF_W, cx + HALF_W):
            R, G, B = r[xx * bpp], r[xx * bpp + 1], r[xx * bpp + 2]
            line.append(1 if (G > 150 and G - R > 50 and G - B > 90) else 0)
        out.append(line)
    return out


_T = [[1 if ch == '#' else 0 for ch in row] for row in TEMPLATE]
_COLS = [i for i in range(len(_T[0])) if any(r[i] for r in _T)]
_LO = _COLS[0] + WIN_LO_OFF
_HI = _COLS[0] + WIN_HI_OFF


def iou(a: list, b: list, shift: int, lo: int = 0, hi: int = None) -> float:
    """a 固定、b 平移 shift 欄後在 [lo, hi) 欄範圍內的 IoU"""
    n = len(a[0])
    hi = n if hi is None else hi
    inter = union = 0
    for ra, rb in zip(a, b):
        for i in range(lo, hi):
            j = i + shift
            va = ra[i]
            vb = rb[j] if 0 <= j < n else 0
            inter += 1 if (va and vb) else 0
            union += 1 if (va or vb) else 0
    return inter / union if union else 0.0


def score(mask: list) -> tuple:
    """→ (整體 IoU, 窗口 IoU)：取整體 IoU 最高的平移量，再算該平移下的窗口 IoU"""
    best = max((iou(_T, mask, s), s) for s in SHIFTS)
    return best[0], iou(_T, mask, best[1], _LO, _HI)


def is_level1(mask: list) -> bool:
    if sum(sum(r) for r in mask) < 25:       # 綠字太少 = 卡片是空格 / 被遮住
        return False
    g, w = score(mask)
    return g >= GLOBAL_MIN and w >= WINDOW_MIN


def card_is_level1(png_path: str, cx: int, cy: int) -> tuple:
    """截圖檔 → (是不是 1 級, 整體 IoU, 窗口 IoU)"""
    import pngread
    w, h, bpp, rows = pngread.decode(Path(png_path).read_bytes())
    m = green_mask(rows, bpp, cx, cy)
    g, wi = score(m)
    return (sum(sum(r) for r in m) >= 25 and g >= GLOBAL_MIN and wi >= WINDOW_MIN), g, wi
