#!/usr/bin/env python3
"""OCR 文字修正表（標準函式庫；全部工具共用一張表）。
Windows OCR 常把中文拆成部首（三點水「氵」與右半分開）或認成形近字；這裡只收實際遇過的。
  fix(text)   → 先合併拆開的雙字（PAIR_FIX），再換形近單字（CHAR_FIX）
原本分散在 dailyquest1920.py 的 STR_FIX（雙字）與 OCR_FIX（單字）兩張表，2026-10-15 合併到這裡（讀每日任務頁也要套雙字，
例：「蛋氵十」→「蛋汁」，之前只套單字表 → 該項變空字串）。
注意：CHAR_FIX 是「材料 / 道具名」用的混淆表（梅 / 悔 / 晦 → 海 等），套到人名 / 寵物名前要先確認不會改壞
（uikit.snap_pet 只在原字串對不上時才用修正後的字串再比一次）。
"""

# 雙字：OCR 把三點水拆開（2026-10-14 深海魚 → 氵罙氵每；蛋汁 → 蛋氵十）
PAIR_FIX = {'氵罙': '深', '氵每': '海', '氵睪': '澤', '氵羊': '洋', '氵十': '汁'}

# 單字：形近字 / 異體字（部分 key 與 value 看起來一樣，是不同碼位的相容字）
CHAR_FIX = {'盬': '鹽', '悔': '海', '梅': '海', '臽': '魚', '晋': '普', '曬': '曬', '幹': '幹', '淸': '清', '雞': '雞', '睪': '澤', '杮': '柿', '爓': '爛', '渘': '深', '晦': '海'}


def fix(text: str) -> str:
    """OCR 文字 → 套修正表（先雙字、再單字）；None / 空字串回 ''"""
    t = text or ''
    for k, v in PAIR_FIX.items():
        t = t.replace(k, v)
    return ''.join(CHAR_FIX.get(c, c) for c in t)
